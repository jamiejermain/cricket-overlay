#!/usr/bin/env bash
# Deploys the cricket-live backend to the personal AWS account and writes backend.js.
# Usage: infra/deploy.sh            (always uses the "songbook" profile = account 730335344374)
set -euo pipefail
cd "$(dirname "$0")/.."

PROFILE=songbook
REGION=ap-southeast-2
EXPECTED_ACCOUNT=730335344374
STACK=cricket-live
BUCKET="cricket-live-artifacts-${EXPECTED_ACCOUNT}"
AWS="aws --profile $PROFILE --region $REGION"

ACCOUNT=$($AWS sts get-caller-identity --query Account --output text)
if [ "$ACCOUNT" != "$EXPECTED_ACCOUNT" ]; then
  echo "Refusing to deploy: profile $PROFILE is account $ACCOUNT, expected $EXPECTED_ACCOUNT" >&2; exit 1
fi

# Private bucket that holds the packaged function code
if ! $AWS s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  $AWS s3api create-bucket --bucket "$BUCKET" --create-bucket-configuration LocationConstraint=$REGION >/dev/null
  $AWS s3api put-public-access-block --bucket "$BUCKET" \
    --public-access-block-configuration BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true
  $AWS s3api put-bucket-tagging --bucket "$BUCKET" --tagging 'TagSet=[{Key=project,Value=cricket-live}]'
fi

PARAMS=()
if ! $AWS cloudformation describe-stacks --stack-name "$STACK" >/dev/null 2>&1; then
  # first deploy only: generate the PlayHQ webhook secret (kept on later deploys)
  PARAMS=(--parameter-overrides "PlayHQWebhookSecret=$(openssl rand -hex 24)")
fi

$AWS cloudformation package --template-file infra/template.yaml --s3-bucket "$BUCKET" \
  --output-template-file infra/.packaged.yaml >/dev/null
$AWS cloudformation deploy --template-file infra/.packaged.yaml --stack-name "$STACK" \
  --capabilities CAPABILITY_IAM CAPABILITY_AUTO_EXPAND --tags project=cricket-live \
  --no-fail-on-empty-changeset ${PARAMS[@]+"${PARAMS[@]}"}

API=$($AWS cloudformation describe-stacks --stack-name "$STACK" --query "Stacks[0].Outputs[?OutputKey=='ApiUrl'].OutputValue" --output text)
cat > backend.js <<EOF
// Generated by infra/deploy.sh — where the scorer and overlay talk to.
window.CRICKET_BACKEND = { api: '$API' };
EOF
echo "Deployed. API: $API"
